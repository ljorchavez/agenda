/**
 * The allergy group a medicine falls in for this patient, or null. `allergies` is free text from
 * the record ("Penicilina, mariscos").
 */
export function allergyConflict(allergies: string | null | undefined, medicine: string): string | null {
  if (!allergies || !medicine.trim()) return null;
  const a = fold(allergies);
  if (/^\s*(niega|negad|ningun|no conocid|sin alerg)/.test(a)) return null;
  const m = fold(medicine);
  for (const g of ALLERGY_GROUPS) {
    if (g.says.some((s) => a.includes(s)) && g.drugs.some((d) => m.includes(d))) return g.name;
  }
  // Same active ingredient written in the allergies (first word, at least 5 letters)
  const first = m.split(/[\s/]+/)[0] ?? '';
  if (first.length >= 5 && a.includes(first.slice(0, 6))) return first;
  return null;
}
