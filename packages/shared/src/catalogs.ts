const fold = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
const INDEX = CIE10_COMMON.map(([code, title]) => ({ code, title, key: fold(`${code} ${code.replace('.', '')} ${title}`) }));

/** Searches by code ("E11", "e119") or words in any order ("diabetes tipo 2"). */
export function searchCie10(query: string, limit = 8): { code: string; title: string }[] {
  const words = fold(query).split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const q = fold(query).replace(/\s+/g, '');
  return INDEX.filter((r) => words.every((w) => r.key.includes(w)))
    .sort((a, b) => Number(!fold(a.code).replace('.', '').startsWith(q)) - Number(!fold(b.code).replace('.', '').startsWith(q)))
    .slice(0, limit)
    .map(({ code, title }) => ({ code, title }));
}

